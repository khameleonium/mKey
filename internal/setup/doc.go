// Package setup — модуль диагностики и настройки окружения mKey (T1.5, SPEC §5.11).
//
// Сейчас модуль предоставляет контракт contracts.Doctor:
//   - Run выполняет проверки (ядро, сессия, init-система, модуль uinput, доступ к
//     /dev/uinput и /dev/input/event*, правила mKey, средство повышения прав,
//     каталог времени выполнения) и возвращает результаты с i18n-ключами сообщений;
//   - Fix выполняет автоматическое исправление — запускает `mkey privileged install-rules`
//     через выбранный бэкенд повышения прав (pkexec, sudo, окно терминала…).
//
// Проверки только читают систему и ничего не меняют. Все обращения к системе идут
// через интерфейс sysProbe, поэтому проверки тестируются на фейковой системе.
// Сведения о сессии и платформе модуль берёт из контрактов contracts.Session и
// contracts.Platform; если соответствующий модуль отключён, проверка пропускается.
//
// Установка, автозапуск и удаление программы появятся здесь в фазе 4.
