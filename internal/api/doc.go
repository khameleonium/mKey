// Package api — модуль HTTP API демона mKey (T2.5, SPEC §9, D9, SEC-5).
//
// Один набор обработчиков доступен через два транспорта:
//   - Unix-сокет <runtime>/mkey.sock (права 0600, каталог 0700) — для CLI; доверенный канал:
//     подключиться может только владелец файла, поэтому токен не нужен;
//   - TCP 127.0.0.1:<port> (по умолчанию 17420) — для веб-интерфейса; защищён:
//     проверка заголовка Host (от DNS rebinding), Origin для изменяющих запросов (от CSRF)
//     и токен (заголовок Authorization: Bearer или cookie после входа по ссылке /?t=<токен>).
//     Токен случайный, создаётся при каждом запуске и лежит в <runtime>/token (0600).
//
// Ошибки возвращаются в едином формате {"error": {"code", "message", "details"}}; сообщение
// переводится на язык из заголовка Accept-Language. Обработчики получают сервисы других
// модулей через контракты; отсутствующий сервис (модуль отключён) даёт ошибку 503.
//
// Описание эндпоинтов — docs/openapi.yaml.
