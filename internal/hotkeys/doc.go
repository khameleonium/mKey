// Package hotkeys — модуль горячих клавиш mKey (T3.3, T3.4, SPEC §5.4).
//
// Модуль ставит себя синхронным обработчиком событий модуля input (contracts.InputHandler)
// и в потоке чтения, без задержек (NFR-1):
//   - ведёт состояние зажатых клавиш (contracts.KeyState: условия key_state, Lua is_down, `mkey wait key`);
//   - применяет переназначения клавиш из проектов (remaps, FR-HK-4);
//   - распознаёт триггеры, которые он регистрирует в точке расширения PointTrigger:
//     hotkey (press, release, hold, double, toggle; consume), sequence (последовательность
//     клавиш), hotstring (набранное слово, как ::btw:: в AHK);
//   - решает, какие события «съесть» (consume): для этого просит модуль input захватить
//     устройства, на которых есть такие клавиши (SetGrabPolicy).
//
// Правило сочетаний: срабатывание по нажатию последней клавиши сочетания, когда остальные
// клавиши сочетания зажаты, а лишних модификаторов (Ctrl, Shift, Alt, Super) нет. Лишние
// обычные клавиши не мешают (удобно в играх: F8 срабатывает и при зажатой W).
//
// Модификаторы горячей клавиши приложения видят зажатыми; перед действиями их можно
// временно отпустить через passthrough-устройство (Fire.Modifiers, FR-HK-3).
//
// Колбэки срабатываний вызываются вне блокировки модуля и должны возвращаться быстро.
