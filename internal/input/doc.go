// Package input — модуль чтения физических устройств ввода (T1.3, SPEC §4.1).
//
// Модуль открывает все устройства /dev/input/event*, классифицирует их (клавиатура,
// мышь, геймпад…) и раздаёт их события подписчикам через контракт contracts.InputSource.
// Подключение и отключение устройств отслеживается через inotify на каталоге /dev/input
// (библиотека fsnotify). Права на только что появившийся файл устройства udev выставляет
// с небольшой задержкой, поэтому при EACCES открытие повторяется несколько раз.
//
// Собственные виртуальные устройства mKey (имя с contracts.VirtualNamePrefix или phys
// с contracts.VirtualPhysPrefix) никогда не читаются — иначе нажатия, отправленные
// самим mKey, вызывали бы его же хоткеи (петля обратной связи).
//
// Нет прав на устройства — не ошибка модуля: он работает, а список недоступных
// устройств виден в Status() и в диагностике (пользователь выдаёт права в мастере).
// Когда права появляются (событие смены атрибутов файла), устройства открываются автоматически.
//
// Захват устройств (grab.go, FR-HK-2): по политике модуля hotkeys устройство захватывается
// (EVIOCGRAB), а то, что не «съели» горячие клавиши, передаётся программам через passthrough-копию
// на uinput. Экстренная остановка (SEC-1) и сторожевой таймер (SEC-3) снимают захват.
