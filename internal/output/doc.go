// Package output — модуль виртуальных устройств mKey (T1.2, SPEC §4.1).
//
// Модуль создаёт через uinput основные виртуальные устройства — клавиатуру
// («mKey Keyboard») и мышь («mKey Mouse») — и предоставляет их через контракт
// contracts.VirtualDevices. Устройства создаются один раз при старте и живут всё время
// работы: композитору нужно время, чтобы подхватить новое устройство (FR-VD-2),
// поэтому первые нажатия ждут окончания «прогрева» (настройка settle_ms).
//
// Каждое устройство помнит зажатые клавиши. При остановке модуля, отмене макроса
// или вызове ReleaseAll всё зажатое отпускается (SEC-2). Если процесс падает, ядро само
// уничтожает uinput-устройства, и зажатые клавиши отпускаются системой.
//
// Если /dev/uinput недоступен (нет модуля ядра или прав), модуль не падает: он работает
// в состоянии «недоступно» и возвращает contracts.ErrOutputUnavailable — пользователь
// увидит это в диагностике и сможет выдать права (SPEC §5.11). При следующем обращении
// модуль снова пытается создать устройства.
//
// Имена и phys всех устройств начинаются с contracts.VirtualNamePrefix и
// contracts.VirtualPhysPrefix — по ним модуль input исключает их из чтения.
