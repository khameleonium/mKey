// Package engine — модуль выполнения макросов и событий проектов mKey (T2.3, T3.2).
//
// События (events.go): проекты из хранилища проверяются и взводятся — триггеры, условия и
// действия берутся из точек расширения (встроенные — builtin*, остальные — модули и плагины);
// политика повторного запуска (FR-EV-5), переменные (vars.go), переключатели.
//
// Макросы (runner.go, contracts.SequenceRunner): принимает текст макроса,
// разбирает и компилирует его библиотекой internal/lib/dsl и выполняет план шагов через
// виртуальные устройства (contracts.VirtualDevices).
//
// Гарантии исполнителя:
//   - каждый запуск макроса — отдельный «раннер» со своим контекстом отмены; StopAll
//     прерывает все раннеры, любая пауза прерывается мгновенно;
//   - раннер помнит, что он зажал; при завершении (успешном, с ошибкой или по отмене)
//     всё это отпускается (FR-DSL-5, SEC-2);
//   - текст набирается по текущей раскладке пользователя (contracts.LayoutProvider):
//     mKey сам зажимает Shift, если символу он нужен, и не трогает Shift, зажатый макросом
//     (тогда Shift действует на символ, как при ручном наборе). Символ из другой раскладки
//     набирается с временным переключением раскладки, если окружение это умеет.
//
// Ограничения: учёт CapsLock при наборе текста и вставка символов, которых нет в раскладках,
// через буфер обмена — фаза 8 (FR-AD-4).
