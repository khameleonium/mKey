// Package registry реализует реестры ядра mKey:
//
//   - Services — реестр сервисов (contracts.ServiceRegistry): модули публикуют в нём
//     реализации контрактов и получают реализации, опубликованные другими модулями;
//   - Extensions — реестры точек расширения (contracts.ExtensionRegistry): типы действий,
//     триггеров, адаптеры и т.д., которые регистрируют модули и плагины;
//   - Manager — менеджер жизненного цикла модулей: Init → Start → Stop, разделение
//     на обязательные (core) и необязательные модули, включение/отключение по конфигу.
//
// Ошибка необязательного модуля не роняет программу: модуль помечается как сбойный,
// его ресурсы освобождаются, остальные модули продолжают работу (NFR-7, NFR-11).
// Ошибка обязательного модуля останавливает запуск.
//
// Пакет может импортировать только internal/contracts и internal/lib/*.
