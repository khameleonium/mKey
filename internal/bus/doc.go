//
// Шина — простой in-memory pub/sub. Публикация никогда не блокирует отправителя:
// у каждого подписчика свой буферизованный канал, и если подписчик не успевает
// читать, новые события для него отбрасываются (счётчик потерь доступен через Dropped).
// Это важно, потому что шину используют и горячие пути ввода, которые нельзя тормозить.
//
// Темы имеют вид "модуль.событие". Подписка поддерживает точное совпадение,
// шаблон "prefix.*" (все темы с префиксом) и "*" (все темы).
