// Package store — модуль хранилища проектов mKey (T3.1, FR-EV-8, SPEC §8).
//
// Проекты — файлы *.mkey.yaml в каталоге ~/.config/mkey/projects (настройка dir).
// Модуль:
//   - загружает все проекты при старте и публикует contracts.Projects;
//   - следит за каталогом (fsnotify) и перечитывает изменённые файлы на лету; если файл
//     с ошибкой — продолжает работать прежняя версия, а ошибка видна в состоянии проекта
//     и на шине (TopicProjectError);
//   - включает и выключает проекты и события, меняя поле enabled прямо в файле: правка идёт
//     через дерево YAML, поэтому комментарии и порядок ключей сохраняются;
//   - импортирует проекты (новый проект выключен, пока пользователь его не проверит, SEC-7);
//   - при первом запуске создаёт выключенный проект-пример с пояснениями.
//
// Файлы записываются атомарно (временный файл + переименование), чтобы демон никогда не
// прочитал наполовину записанный файл.
