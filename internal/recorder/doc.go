// Package recorder — модуль mKey «recorder»: запись ввода с физических устройств и её
// воспроизведение через виртуальные устройства mKey (этап 6, FR-REC-1…4).
//
// Запись: события клавиатур и мышей (по умолчанию) с метками времени ядра пишутся в файл
// <имя>.mkrec в каталоге записей (~/.local/share/mkey/recordings, формат — internal/lib/mkrec).
// Начать и закончить запись можно командой (`mkey rec`, API) или сочетанием клавиш
// (по умолчанию Ctrl+Alt+R — работает в любой программе, например в игре). Сочетание,
// которым запись остановили, из неё вырезается; отпускания клавиш, нажатых до начала записи,
// не записываются.
//
// Воспроизведение (`mkey play`, действие play в проектах): пакеты событий отправляются
// в виртуальные клавиатуру и мышь в записанном темпе (с учётом скорости и повторов).
// Клавиши, нажатые воспроизведением, отпускаются при любой остановке: конец записи, `mkey stop`,
// экстренная остановка (SEC-1/SEC-2). Геймпады и тач пока записываются, но не воспроизводятся.
//
// Модуль пользуется контрактами contracts.InputSource (события и устройства) и
// contracts.VirtualDevices (вывод), предоставляет contracts.Recorder и contracts.Player
// и регистрирует действие play. Без input запись недоступна, без output — воспроизведение.
