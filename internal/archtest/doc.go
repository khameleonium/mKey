// Package archtest проверяет архитектурные границы mKey (SPEC §4.3, AGENTS.md §4.1).
//
// Тест разбирает импорты всех Go-файлов в internal/ (кроме тестовых) и проверяет правила:
//
//   - internal/lib/*        — только другие internal/lib/*;
//   - internal/contracts    — только internal/lib/*;
//   - internal/bus, i18n, registry (инфраструктура ядра) — только contracts и lib;
//   - любой модуль internal/<X> — только contracts, registry, bus, i18n, lib
//     и собственные подпакеты internal/<X>/...;
//   - internal/app          — может импортировать всё (это сборка программы).
//
// Модули не импортируют друг друга: нужная функциональность берётся через контракты.
// Правило проверяется этим тестом, а не depguard, потому что depguard не умеет
// разрешать модулю импорт собственных подпакетов при запрете чужих.
