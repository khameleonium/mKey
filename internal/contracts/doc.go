// Package contracts содержит интерфейсы, через которые модули mKey общаются друг с другом.
//
// Это единственное, что модули знают друг о друге: модуль не импортирует другой модуль,
// а получает нужный ему контракт из реестра сервисов (см. Host.Services) или слушает
// события шины (см. Bus). Так каждый модуль можно дорабатывать, тестировать на фейках
// и отключать независимо от остальных (SPEC §4.3, D12).
//
// Основные типы:
//   - Module — единица функциональности со своим жизненным циклом (Init → Start → Stop);
//   - Host — всё, что ядро даёт модулю: логгер, конфиг, i18n, сервисы, шину, точки расширения;
//   - ServiceRegistry — реестр сервисов (реализаций контрактов) между модулями;
//   - ExtensionRegistry — реестры точек расширения (типы действий, триггеров, адаптеры…);
//   - Bus — внутренняя шина событий.
//
// Как расширять: новый контракт между модулями добавляется сюда отдельным коммитом
// с обоснованием. Контракты — публичное обещание плагинам (через pkg/pluginsdk),
// поэтому ломающие изменения делаются только через ADR (AGENTS.md §4.1).
//
// Пакет не должен импортировать никакие пакеты mKey, кроме internal/lib/*.
