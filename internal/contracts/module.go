package contracts

import (
	"context"
	"log/slog"
)

// Module — самостоятельная часть функциональности mKey со своим жизненным циклом.
//
// Порядок вызовов, который гарантирует ядро: Init (для всех модулей по порядку
// регистрации) → Start (в том же порядке) → Stop (в обратном порядке).
// Stop вызывается и для модулей, у которых Start завершился ошибкой, поэтому
// Stop должен быть безопасен при частично инициализированном состоянии.
type Module interface {
	// ID возвращает уникальный идентификатор модуля, например "recorder".
	// Он же — имя секции модуля в config.yaml и префикс его i18n-ключей.
	ID() string
	// Init получает зависимости от хоста и регистрирует сервисы и точки расширения.
	// В Init нельзя запускать фоновую работу — только подготовка.
	Init(ctx context.Context, host Host) error
	// Start запускает фоновую работу модуля. Не должен блокироваться надолго:
	// долгие циклы запускаются в горутинах и завершаются по Stop.
	Start(ctx context.Context) error
	// Stop останавливает модуль и освобождает все его ресурсы
	// (включая зажатые виртуальные клавиши и захваченные устройства).
	Stop(ctx context.Context) error
}

// Host — всё, что ядро предоставляет модулю при инициализации.
type Host interface {
	// Logger возвращает логгер, уже помеченный идентификатором модуля.
	Logger() *slog.Logger
	// Config возвращает секцию config.yaml, относящуюся к этому модулю.
	Config() ConfigSection
	// I18n возвращает переводчик пользовательских сообщений.
	I18n() Translator
	// Services возвращает общий реестр сервисов (контрактов между модулями).
	Services() ServiceRegistry
	// Extensions возвращает реестры точек расширения.
	Extensions() ExtensionRegistry
	// Bus возвращает внутреннюю шину событий.
	Bus() Bus
}

// ConfigSection — секция конфигурации одного модуля.
type ConfigSection interface {
	// Decode заполняет структуру v значениями из секции.
	// Если секции нет, v остаётся без изменений (значения по умолчанию).
	Decode(v any) error
}

// Translator переводит ключи сообщений на язык пользователя.
type Translator interface {
	// T возвращает перевод ключа key, подставляя параметры вида {name} из args.
	// Если перевода нет ни на одном языке, возвращает сам ключ.
	T(key string, args ...Arg) string
	// Lang возвращает текущий язык интерфейса ("ru", "en").
	Lang() string
	// WithLang возвращает переводчик на язык lang (например, для ответа API на языке клиента).
	// Неизвестный язык заменяется языком по умолчанию.
	WithLang(lang string) Translator
}

// Arg — именованный параметр для подстановки в перевод.
type Arg struct {
	// Name — имя плейсхолдера без фигурных скобок.
	Name string
	// Value — значение, которое будет подставлено через fmt.Sprint.
	Value any
}
