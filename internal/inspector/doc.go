// Package inspector — инспектор устройств ввода (этап 7, FR-DEV-1).
//
// Модуль предоставляет сервис contracts.Inspector: подробные сведения о каждом устройстве,
// которое открыл модуль input, — постоянные имена udev (by-id, by-path; lib/evdev.ReadLinks),
// все клавиши и кнопки, оси с диапазонами, переключатели, индикаторы и виды отдачи — с именами
// ядра и, где есть, с именами для макросов (lib/keys). Поиск устройства — по пути, имени файла,
// постоянному имени или части названия (Find).
//
// Сведения отдают API (GET /api/v1/devices/{ref}), команда `mkey devices inspect` и раздел
// «Устройства» в окне. Модуль только читает: не захватывает устройства и не пишет в них.
//
// Дальше (T7.2–T7.4) здесь появятся авто-ID неизвестных устройств и кнопок (UnKey, 001),
