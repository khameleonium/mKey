// Package desktop — модуль десктоп-адаптеров mKey (SPEC §5.8, ADR-0006).
//
// Адаптеры дают то, что зависит от окружения рабочего стола и недоступно через evdev:
// раскладку клавиатуры, а в фазе 8 — активное окно, цвет пикселя и позицию курсора.
// Модуль выбирает адаптер по сведениям о сессии (contracts.Session) и публикует
// соответствующие контракты.
//
// Сейчас (этап 2, частично перенесённая задача T8.9) реализован только contracts.LayoutProvider:
//   - kde — KDE Plasma через D-Bus org.kde.keyboard /Layouts: текущая раскладка, список,
//     переключение (подпакет kde);
//   - gnome — GNOME через gsettings org.gnome.desktop.input-sources: текущая раскладка
//     и список, без переключения (подпакет gnome);
//   - config — остальные окружения: раскладки из настроек модуля (layouts, layout),
//     без определения текущей раскладки и без переключения.
//
// Если адаптер окружения не работает (нет D-Bus, другая версия KDE), модуль пишет
// предупреждение в журнал и использует config — набор текста продолжает работать
// в раскладке из настроек.
