// Package i18n переводит пользовательские сообщения mKey (CLI, ошибки API, уведомления).
//
// Переводы лежат в locales/<язык>.json (плоская карта «ключ → текст») и встраиваются
// в бинарник. Поддерживаемые языки: ru и en (NFR-9). Ключи именуются как
// "<модуль>.<подсистема>.<сообщение>", например "cli.version.short".
// Плейсхолдеры в тексте пишутся как {name} и подставляются из contracts.Arg.
//
// Порядок поиска перевода: текущий язык → английский → сам ключ.
// Тест пакета проверяет, что во всех языках одинаковый набор ключей и плейсхолдеров.
//
// Как добавить сообщение: добавьте ключ во все файлы locales/*.json с одинаковыми
// плейсхолдерами. Фронтенд использует свои файлы переводов (web/src/lib/i18n).
