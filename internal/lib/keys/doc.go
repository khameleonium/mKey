// Package keys — таблица имён клавиш mKey ↔ коды evdev (SPEC §5.1, T1.1).
//
// Имена клавиш — явные и регистронезависимые: {Ctrl}, {ctrl} и {CTRL} — одно и то же.
// Каждая клавиша имеет каноническое имя (как его выводит форматтер и GUI) и алиасы.
// Имена обозначают физические клавиши US-раскладки, как в evdev: {Q} на русской
// раскладке даст «й», а {A} — строчную «a».
//
// Пространства имён:
//   - основное (Lookup): клавиатура и мышь — A, Enter, Ctrl, Mouse0…;
//   - геймпад (LookupGamepad): South/East/…, LB/RB, Start… Имена вроде A/B/X/Y
//     конфликтуют с буквами, поэтому доступны только с префиксом устройства ({pad2.A});
//   - оси (LookupAxis): LX, LY, RX, RY, LT, RT, DPadX, DPadY.
//
// Модификаторы без стороны (Ctrl, Shift, Alt, Super) при отправке означают левую
// клавишу, а при распознавании хоткея — любую из двух (Key.Matches).
//
// Suggest подсказывает ближайшее имя при опечатке (FR-DSL-3).
