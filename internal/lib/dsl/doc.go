// Package dsl — язык макросов mKey: разбор, форматирование и компиляция (T2.2, T2.3, docs/dsl.md).
//
// Путь строки макроса: текст → Parse → дерево разбора ([]Node) → Compile → план ([]Step) →
// исполнитель (модуль internal/engine).
//
//   - Parse проверяет синтаксис и имена клавиш и возвращает дерево с позициями (строка, столбец).
//     Ошибки — *Error с i18n-кодом и параметрами (FR-DSL-3), текст для пользователя формирует вызывающий.
//   - Format превращает дерево обратно в текст в каноническом виде (FR-DSL-4): имена клавиш
//     как в таблице, без лишних пробелов. Само дерево отдаётся GUI в JSON для конструктора блоков.
//   - Compile превращает дерево в план шагов с уже найденными кодами клавиш и устройствами.
//     Устройства определяет Resolver: по умолчанию DefaultResolver (клавиатура и мышь mKey);
//     виртуальные устройства проектов и кнопки устройств (pad2, Sega…) — DeviceResolver.
//
// Пакет — чистая библиотека: ничего не выполняет и не зависит от модулей.
