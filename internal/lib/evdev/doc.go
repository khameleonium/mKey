// Package evdev — тонкая pure-Go обёртка над интерфейсами ядра Linux для ввода:
// evdev (/dev/input/event*, чтение физических устройств) и uinput (/dev/uinput,
// создание виртуальных устройств). Решение: ADR-0001, ADR-0018.
//
// Это библиотека без жизненного цикла: она не запускает горутин и не хранит состояние
// программы — только открывает файлы устройств и выполняет ioctl. Жизненным циклом
// (hotplug, подписки, освобождение клавиш) управляют модули internal/input и internal/output.
//
// Основные типы:
//   - Event — событие ввода (struct input_event ядра);
//   - Device — открытое физическое устройство: сведения, возможности, чтение, grab;
//   - Info, ID, AbsInfo, Capabilities — описание устройства;
//   - UInput — созданное виртуальное устройство и отправка в него событий;
//   - ProcDevice — запись из /proc/bus/input/devices (доступна без прав на устройства).
//
// Коды событий (EvKey, KeyA, BtnLeft…) сгенерированы из linux/input-event-codes.h
// командой tools/gencodes (файл codes_gen.go). Поддерживаются только 64-битные
// архитектуры (amd64, arm64): от этого зависит размер struct input_event.
