// Package tray — модуль mKey «tray»: значок в системном трее (FR-UI-9, T5.9).
//
// Значок показывает, работает ли mKey (синий) или приостановлен после экстренной остановки
// (красный). Щелчок по значку открывает веб-интерфейс. Меню (решение владельца, 2026-10-01) —
// разделы через разделитель:
//   - «Открыть mKey»;
//   - «Проекты ▸» (галочка — включён; щелчок включает или выключает), «Запустить событие ▸»
//     (события «только вручную» включённых проектов);
//   - «● Начать запись» / «■ Закончить запись», «Повторить запись ▸» (последние записи, отсчёт
//     3 с, чтобы переключиться в нужное окно), «Остановить все макросы»;
//   - «Открыть папку проектов», «Открыть папку записей»;
//   - «Экстренная остановка» / «Продолжить работу», «Выйти из mKey».
//
// Итоги действий (запись началась, сохранена, ошибки) — уведомлениями.
//
// Протокол трея (StatusNotifierItem по D-Bus, меню с подменю и галочками) реализует библиотека
// internal/lib/sni. Модуль пользуется контрактами GUIServer, URLOpener, InputSource, KeyState,
// Lifecycle, Projects, Events, SequenceRunner, Recorder, Player, Notifier и местами «Где что
// лежит» (PointPlace); меню пересобирается при экстренной остановке, возобновлении, изменении
// проектов и начале/конце записи. Любой сервис может отсутствовать — тогда его пунктов нет.
//
// Модуль необязательный: без сессионной шины D-Bus или без панели трея (GNOME без расширения
// AppIndicator) mKey работает как обычно, значка просто нет. Отключить значок:
// `modules: { tray: { enabled: false } }` в config.yaml.
