// Package tray — модуль mKey «tray»: значок в системном трее (FR-UI-9, T5.9).
//
// Значок показывает, работает ли mKey (синий) или приостановлен после экстренной остановки
// (красный). Щелчок по значку открывает веб-интерфейс, меню содержит пункты
// «Открыть mKey», «Экстренная остановка» / «Продолжить работу» и «Выйти из mKey».
//
// Протокол трея (StatusNotifierItem по D-Bus) реализует библиотека internal/lib/sni.
// Модуль пользуется контрактами: contracts.GUIServer (адрес окна, модуль api),
// contracts.URLOpener (браузер, модуль desktop), contracts.InputSource (экстренная остановка),
// contracts.KeyState (возобновление), contracts.Lifecycle (выход); следит за темами шины
// TopicEmergency и TopicResumed. Любой из этих сервисов может отсутствовать — тогда
// соответствующий пункт меню не показывается.
//
// Модуль необязательный: без сессионной шины D-Bus или без панели трея (GNOME без расширения
// AppIndicator) mKey работает как обычно, значка просто нет. Отключить значок:
// `modules: { tray: { enabled: false } }` в config.yaml.
