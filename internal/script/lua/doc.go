// Package lua — модуль скриптов Lua для mKey (T3.6, FR-LUA-1..3, docs/lua-api.md).
//
// Модуль регистрирует действие lua (точка расширения PointAction). Скрипт задаётся строкой
// прямо в проекте или файлом из ~/.config/mkey/scripts. Каждое выполнение получает
// собственное состояние Lua (LState) с модулем mkey, привязанным к выполняемому событию:
// нажатия идут через тот же раннер, что и остальные действия события, поэтому зажатое
// скриптом отпускается по завершении события.
//
// Отмена: состояние Lua получает контекст выполнения (LState.SetContext) — при остановке
// скрипт прерывается даже в цикле без вызовов mkey.*, а mkey.sleep прерывается сразу.
//
// Стандартные библиотеки Lua (os, io) доступны: это скрипты самого пользователя. Чужие проекты
// со скриптами при импорте выключены и требуют проверки (SEC-7).
