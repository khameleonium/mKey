// Package shell — модуль bash-скриптов для mKey (T3.7, FR-SH-1..3).
//
// Модуль регистрирует действие shell. Скрипт задаётся строкой в проекте или файлом из
// ~/.config/mkey/scripts и выполняется командой bash (если bash нет — sh) в отдельной группе
// процессов. Окружение скрипта:
//   - MKEY_SOCKET — сокет API демона (команды `mkey send`, `mkey var` работают без поиска демона);
//   - MKEY_PROJECT, MKEY_EVENT — выполняемое событие (по ним `mkey var` находит проект);
//   - MKEY_VAR_<ИМЯ> — значения переменных проекта (только чтение, имя в верхнем регистре);
//   - PATH начинается с каталога исполняемого файла mkey.
//
// Вывод скрипта (stdout и stderr) пишется в журнал демона. Ограничение времени — timeout_ms
// (по умолчанию 60 с). Остановка события отправляет группе процессов SIGTERM, через 2 секунды —
// SIGKILL, чтобы не осталось «зависших» дочерних процессов.
package shell
